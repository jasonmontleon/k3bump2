#!/usr/bin/env python3
# mkextra.py DUMPDIR LIBRARY  ->  extra.h, extra.bin
# Adds to the snapshot (snap.h, snap.bin) every page of librustc_driver's code that had a page-table entry in the
# dead process (DUMPDIR/pm.3ff3000000 = /proc/PID/pagemap of that mapping) and is not in the snapshot
# yet, with the bytes of the library file.  The page lib+0x2a20000 had no entry; its bytes are kept
# separately (extra.bin's last page) for the control and the cache check.
import struct, re, sys
BASE, TEXT, P = 0x3ff3000000, 0x338b000, 0x2a20000
dump, libf = sys.argv[1], sys.argv[2]
lib = open(libf, 'rb').read()
pm = open(dump + '/pm.%x' % BASE, 'rb').read()
ent = struct.unpack('<%dQ' % (len(pm) // 8), pm)
assert len(ent) == TEXT >> 12 and not ent[P >> 12] >> 63
have = {int(a, 16) for a, k in re.findall(r'\{(0x[0-9a-f]+)UL, (\d)\}', open('snap.h').read())}
extra = [BASE + (i << 12) for i in range(len(ent)) if ent[i] >> 63 and BASE + (i << 12) not in have]
with open('extra.bin', 'wb') as f:
    for a in extra: f.write(lib[a - BASE:a - BASE + 4096])
    f.write(lib[P:P + 4096])
with open('extra.h', 'w') as f:
    f.write('/* generated by mkextra.py: code pages of librustc_driver that were mapped in the dead process (dump-1) */\n')
    f.write('#define EXTRA_NPAGES %d\n' % len(extra))
    f.write('static const unsigned long extra_pages[EXTRA_NPAGES] = {\n')
    for i in range(0, len(extra), 6): f.write('\t' + ' '.join('0x%xUL,' % a for a in extra[i:i + 6]) + '\n')
    f.write('};\n')
print(len(extra), 'extra pages;', sum(1 for i in range(len(ent)) if ent[i] >> 63), 'mapped in the dump;', len([a for a in have if BASE <= a < BASE + TEXT]), 'already in the snapshot')
